"""Write the measured-performance section of README.md and DOCUMENTATION.md from the
results files (results/runtime/runtime.json, results/measured_results.json,
results/baselines.json). The section sits between <!-- PERF --> and <!-- /PERF -->;
re-running the script replaces it. No hand-entered numbers.

  python docs/fill_perf.py
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RES = os.path.join(ROOT, "results")


def load(p):
    p = os.path.join(RES, p)
    return json.load(open(p, encoding="utf-8")) if os.path.exists(p) else None


RT, MR, BL = load("runtime/runtime.json"), load("measured_results.json"), load("baselines.json")


def f(v, nd=1):
    return "–" if v is None else f"{float(v):.{nd}f}"


def section(img_prefix):
    out = []
    env = (RT or {}).get("env", {})
    out.append(f"All numbers below were measured on **{env.get('gpu', 'NVIDIA GeForce RTX 3060')}** "
               f"({round(env.get('gpu_memory_gb', 12))} GB), {env.get('cpu', 'Intel Core i5-14400F').strip()}, 16 GB RAM, "
               f"Windows 11, PyTorch {str(env.get('torch', '2.5.1')).split('+')[0]} + CUDA {env.get('cuda', '12.1')}. "
               "They are generated by `docs/fill_perf.py` from the measured results; the run logs, the aggregated results "
               "and the provenance of every benchmark number are available from the author on request.\n")
    # ---- live
    live, cap = (RT or {}).get("live"), (RT or {}).get("live_cap4gb")
    if live and live.get("stages"):
        out.append("### Live end-to-end (TUM fr1/room replayed at 30 Hz through the full server)\n")
        out.append("| | tracking FPS | frames reaching fusion / s | tracking (median ms) | depth + CG-SSF (median ms) | fusion (median ms) | frame age at fusion (median / p95 ms) | peak GPU memory |")
        out.append("| :-- | --: | --: | --: | --: | --: | --: | --: |")
        for lab, L in (("uncapped", live), ("4 GB cap", cap)):
            if not L or not L.get("stages"):
                continue
            s = L["stages"]
            age = L.get("age_ms") or {}
            out.append(f"| {lab} | {f(s['slam']['fps_mean'])} | {f(s['fusion']['fps_mean'])} | {f(s['slam']['median_ms'])} | "
                       f"{f(s['semantic']['median_ms'])} | {f(s['fusion']['median_ms'])} | {f(age.get('median'), 0)} / {f(age.get('p95'), 0)} | "
                       f"{f(L['gpu']['peak_allocated_mb'] / 1024, 2)} GB |")
        out.append("")
        out.append(f"![live runtime]({img_prefix}live_runtime.png)\n")
    # ---- components
    comp = (RT or {}).get("components") or {}
    if comp:
        bb = {r["tag"]: r for r in (MR or {}).get("tables", {}).get("table6_backbones", [])}
        out.append("### Per-component latency (isolated, median after GPU sync)\n")
        sd = sorted({str(r.get("seeds", "")) for r in bb.values()} - {""})
        out.append("| component | latency (ms) | memory (MB) | TUM fr1 AbsRel of the full system"
                   + (f" (seed {sd[0]})" if len(sd) == 1 else "") + " |")
        out.append("| :-- | --: | --: | --: |")
        rows = [("DISK (1024) + LightGlue", "DISK+LightGlue", None), ("YOLOv8n-seg (320 px)", "YOLOv8n-seg", None),
                ("DPT-Hybrid (default)", "DPT_Hybrid", "cgssf"), ("DPT-Large", "DPT_Large", "cgssf_dptlarge"),
                ("MiDaS-small", "MiDaS_small", "cgssf_midassmall"), ("Depth Anything V2-S", "DepthAnythingV2_Small", "cgssf_dav2s"),
                ("CG-SSF update (CPU)", "CG-SSF update (CPU)", None), ("depth, σ_z, weights (GPU)", "Depth, sigma_z, weights (GPU)", None),
                ("weighted TSDF integration (GPU)", "Weighted TSDF integration (GPU)", None), ("marching cubes (CPU thread)", "Marching cubes (CPU)", None)]
        for name, k, tag in rows:
            c = comp.get(k) or {}
            if "median_ms" not in c:
                continue
            ar = bb.get(tag, {}).get("TUM_AbsRel_pct") if tag else None
            out.append(f"| {name} | {f(c['median_ms'], 2 if c['median_ms'] < 1 else 1)} | {f(c.get('peak_mb'))} | {f(ar) + ' %' if ar is not None else '–'} |")
        out.append("")
        out.append(f"![model latency]({img_prefix}model_latency.png)\n")
    # ---- ablation
    if MR:
        t3 = MR["tables"]["table3_ablation"]
        seeds = sorted({r["seed"] for r in MR["runs"] if r.get("seed") is not None})
        seed_txt = f"seed {seeds[0]}" if len(seeds) == 1 else f"mean over seeds {', '.join(map(str, seeds))}"
        out.append(f"### Full-system ablation (TUM RGB-D fr1 × 9, Replica × 8, {seed_txt})\n")
        out.append("| variant | TUM AbsRel % ↓ | TUM δ₁ % ↑ | TUM SC ×10⁻² ↓ | Replica Acc. cm ↓ | Replica Comp. cm ↓ | Replica F % ↑ | Replica ATE cm ↓ |")
        out.append("| :-- | --: | --: | --: | --: | --: | --: | --: |")
        for r in t3:
            out.append(f"| {r['label']} | {f(r['TUM_AbsRel_pct'])} | {f(r['TUM_delta1_pct'])} | {f(r['TUM_SC_x1e2'])} | {f(r['Replica_Acc_cm'])} | "
                       f"{f(r['Replica_Comp_cm'])} | {f(r['Replica_F_pct'])} | {f(r['Replica_ATE_cm'])} |")
        out.append("")
        T = MR["tests"]
        def t(k):
            return T.get(k) or {}
        out.append("Paired Wilcoxon tests over sequences (full CG-SSF vs. the variant): "
                   f"scale consistency vs. prototype (b) p = {f(t('cgssf_vs_proto_ema:sc').get('p'), 3)}, vs. (e) p = {f(t('cgssf_vs_irls_ema:sc').get('p'), 3)}; "
                   f"AbsRel vs. (e) p = {f(t('cgssf_vs_irls_ema:absrel').get('p'), 3)}; Replica accuracy vs. uniform weights (j) p = {f(t('cgssf_vs_cgssf_uniform:acc_cm').get('p'), 3)}, "
                   f"completion vs. (j) p = {f(t('cgssf_vs_cgssf_uniform:comp_cm').get('p'), 3)}.\n")
        rk = {r["variant"]: r for r in t3}
        a_j, a_k = (rk.get("cgssf_uniform") or {}).get("Replica_Acc_cm"), (rk.get("cgssf") or {}).get("Replica_Acc_cm")
        verb = "more than halves" if a_j and a_k and a_j >= 2 * a_k else "lowers"
        out.append(f"**Reading:** uncertainty-weighted fusion (k) {verb} the Replica accuracy error of uniform weights "
                   f"(j), {f(a_j)} cm to {f(a_k)} cm, at the cost of completion. In the full system, the lightweight front end "
                   "chosen for the 4 GB budget (no bundle adjustment, no loop closure) dominates the remaining error, and the "
                   "filtered variants (e) to (k) differ little in depth accuracy; the paper compares the estimators with "
                   "ground-truth poses.\n")
        out.append(f"![ablation]({img_prefix}ablation.png)\n")
        # ---- trajectory
        ps = {(r["tag"], r["sequence"]): r for r in MR["per_sequence"]}
        fr1 = ["fr1_360", "fr1_desk", "fr1_desk2", "fr1_floor", "fr1_plant", "fr1_room", "fr1_rpy", "fr1_teddy", "fr1_xyz"]
        vals = [ps[("cgssf", q)]["ate_cm"] for q in fr1 if ("cgssf", q) in ps and ps[("cgssf", q)]["ate_cm"] is not None]
        blt = (BL or {}).get("tum_fr1_ate_m", {})
        lv = [100 * blt[k]["values"][9] for k in ("DROID-SLAM", "DPV-SLAM++", "GO-SLAM", "MASt3R-SLAM") if k in blt] or [float("nan")]
        blr = (BL or {}).get("replica_mono_recon", {})
        names = [k for k in blr if not k.startswith("_")]
        acc = [blr[k]["acc_cm"] for k in names]
        cr = [blr[k]["comp_ratio_pct"] for k in names]
        mem = [blr[k]["gpu_mem_gb"] for k in names if "gpu_mem_gb" in blr[k]]
        out.append("### Trajectory (ATE RMSE after Sim(3) alignment)\n")
        fail = [q.replace("fr1_", "fr1/") for q in fr1 if ((ps.get(("cgssf", q)) or {}).get("ate_cm")) is None]
        names = " and ".join([", ".join(fail[:-1]), fail[-1]] if len(fail) > 1 else fail)
        out.append(f"- TUM fr1: {f(sum(vals) / len(vals)) if vals else '–'} cm mean over the {len(vals)}/9 sequences tracked without failure"
                   + (f" ({names} re-initialize)" if fail else "")
                   + f". Published learned dense methods: {f(min(lv))}–{f(max(lv))} cm averaged over all nine "
                   "(as reported in MASt3R-SLAM, Table 1).")
        dyn = ["fr3_walking_xyz", "fr3_walking_halfsphere", "fr3_sitting_xyz"]
        out.append("- TUM fr3 dynamic (with / without person masking): " + ", ".join(
            f"{q.replace('fr3_', '')} {f((ps.get(('cgssf', q)) or {}).get('ate_cm'))} / {f((ps.get(('cgssf_nomask', q)) or {}).get('ate_cm'))} cm" for q in dyn) + ".")
        t4 = MR["tables"]["table4_ours"][0]
        out.append(f"- Replica: {f(t4['ATE_cm'])} cm; reconstruction Acc. {f(t4['Acc_cm'], 2)} cm, Comp. {f(t4['Comp_cm'], 2)} cm, "
                   f"completion ratio {f(t4['CR_pct'])} %, F-score {f(t4['F_pct'])} % (published dense methods: {f(min(acc), 2)}–{f(max(acc), 2)} cm Acc., "
                   f"{f(min(cr))}–{f(max(cr))} % CR, measured by their authors on an RTX 3090 / A100"
                   + (f"; GlORIE-SLAM uses {f(max(mem))} GB of GPU memory" if mem else "") + ").\n")
    return "\n".join(out)


def fill(path, img_prefix):
    s = open(path, encoding="utf-8").read()
    block = "<!-- PERF -->\n\n" + section(img_prefix) + "\n<!-- /PERF -->"
    if "<!-- /PERF -->" in s:
        s = re.sub(r"<!-- PERF -->.*?<!-- /PERF -->", lambda _m: block, s, flags=re.S)
    else:
        s = s.replace("<!-- PERF -->", block, 1)
    open(path, "w", encoding="utf-8").write(s)
    print("filled", path)


if __name__ == "__main__":
    fill(os.path.join(ROOT, "README.md"), "docs/")
    fill(os.path.join(ROOT, "DOCUMENTATION.md"), "docs/")
